export function jokeKey(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

export function pickHebrewJoke(excludeKeys: readonly string[] = []): string {
  const exclude = new Set(excludeKeys.map((k) => k.trim()).filter(Boolean));
  const pool = HEBREW_JOKES.filter((joke) => !exclude.has(jokeKey(joke)));
  const source = pool.length > 0 ? pool : HEBREW_JOKES;
  return source[Math.floor(Math.random() * source.length)]!;
}
